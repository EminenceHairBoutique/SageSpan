"""Emit supabase/migrations/0006_seed_rule_sets.sql from the Python rule registry.

The database verifies calculator receipts against app.rule_sets (id, version,
checksum, PUBLISHED). The seed is generated from the same registry the engine
uses, with checksums computed by the registry (sha256 of canonical JSON of the
definition). A trigger in the database recomputes the checksum from the stored
definition, and tests/test_rule_set_seed.py fails if this file drifts.

Usage: python scripts/export_rule_sets_sql.py            # writes the migration
       python scripts/export_rule_sets_sql.py --check    # exits 1 on drift
"""
from __future__ import annotations

import json
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.financial.canonical import canonical_json  # noqa: E402
from app.financial.rules import ALL_RULE_SETS, RuleSet  # noqa: E402

OUT = ROOT.parent.parent / "supabase" / "migrations" / "0006_seed_rule_sets.sql"
NAMESPACE = uuid.UUID("6f3c2a1e-9b7d-4e0a-8c21-5d4f2b9a7e11")
RETRIEVED_AT = "2026-11-05T00:00:00Z"


def definition_of(r: RuleSet) -> dict:
    return {
        "rule_set_id": r.rule_set_id,
        "version": r.version,
        "effective_from": r.effective_from,
        "effective_to": r.effective_to,
        "parameters": r.parameters,
        "sources": [s.as_dict() for s in r.sources],
    }


def sql_literal(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def parameter_rows(r: RuleSet) -> list[tuple[str, str | None, str | None]]:
    """(parameter_key, value_decimal, value_string). Tables are expanded one row per entry."""
    rows: list[tuple[str, str | None, str | None]] = []
    for key, value in r.parameters.items():
        if isinstance(value, dict) and all(isinstance(v, str) for v in value.values()):
            for sub, v in value.items():
                rows.append((f"{key}.{sub}", v if _is_decimal(v) else None, None if _is_decimal(v) else v))
        elif isinstance(value, (dict, list)):
            rows.append((key, None, canonical_json(value)))
        elif isinstance(value, bool):
            rows.append((key, None, "true" if value else "false"))
        elif isinstance(value, (int, float)):
            rows.append((key, str(value), None))
        else:
            text = str(value)
            rows.append((key, text if _is_decimal(text) else None, None if _is_decimal(text) else text))
    return rows


def _is_decimal(text: object) -> bool:
    try:
        float(str(text))
        return str(text).replace(".", "", 1).replace("-", "", 1).isdigit()
    except ValueError:
        return False


def render() -> str:
    lines = [
        "-- GENERATED by services/calculator/scripts/export_rule_sets_sql.py from app/financial/rules.py. Do not edit by hand.",
        "-- Seeds the rule registry the database uses to verify calculator receipts (app.record_check_run).",
        "-- checksum = sha256(canonical_json(definition)), computed by the Python registry; app.rule_sets_checksum_guard re-verifies it.",
        "",
    ]
    for r in ALL_RULE_SETS:
        rid = uuid.uuid5(NAMESPACE, f"sagespan:rule_set:{r.rule_set_id}@{r.version}")
        definition = definition_of(r)
        approved = "null" if r.status != "PUBLISHED" else sql_literal(RETRIEVED_AT)
        source_url = sql_literal(r.sources[0].url) if r.sources and r.sources[0].url else "null"
        eff_to = sql_literal(r.effective_to.isoformat()) if r.effective_to else "null"
        lines.append(
            "insert into app.rule_sets (id, code, jurisdiction, tax_year, effective_from, effective_to, version, source_url, source_retrieved_at, checksum, status, approved_at, definition)\n"
            f"values ({sql_literal(str(rid))}, {sql_literal(r.rule_set_id)}, 'US-FEDERAL', null, {sql_literal(r.effective_from.isoformat())}, {eff_to}, {sql_literal(r.version)}, {source_url}, {sql_literal(RETRIEVED_AT)}, {sql_literal(r.checksum)}, {sql_literal(r.status)}, {approved}, {sql_literal(canonical_json(definition))}::jsonb)\n"
            "on conflict (code, version) do update set checksum = excluded.checksum, status = excluded.status, approved_at = excluded.approved_at, definition = excluded.definition, effective_from = excluded.effective_from, effective_to = excluded.effective_to, source_url = excluded.source_url;"
        )
        lines.append(f"delete from app.rule_parameters where rule_set_id = {sql_literal(str(rid))};")
        for key, dec, text in parameter_rows(r):
            lines.append(
                f"insert into app.rule_parameters (rule_set_id, parameter_key, value_decimal, value_string) values ({sql_literal(str(rid))}, {sql_literal(key)}, {dec if dec is not None else 'null'}, {sql_literal(text) if text is not None else 'null'});"
            )
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"drift: {OUT} does not match the registry; run python scripts/export_rule_sets_sql.py")
            return 1
        print("rule-set seed matches the registry")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(ALL_RULE_SETS)} rule sets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
