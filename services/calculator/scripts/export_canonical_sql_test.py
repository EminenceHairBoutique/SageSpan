"""Emit supabase/tests/006_canonical_json.test.sql from fixtures/synthetic/canonical.

Three tiers must hash identical bytes: Python (app.financial.canonical), TypeScript
(packages/contracts canonical.ts) and SQL (app.canonical_json). The fixture files
and expected.json are the single source; this script embeds them into a pgTAP test
and tests/test_canonical_fixtures.py fails if the embedded copy drifts.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from app.financial.canonical import canonical_hash, canonical_json  # noqa: E402

FIXTURES = ROOT.parent.parent / "fixtures" / "synthetic" / "canonical"
OUT = ROOT.parent.parent / "supabase" / "tests" / "006_canonical_json.test.sql"

# Structural guarantees independent of the fixtures. Inputs are rendered as JSON text and
# expectations by the Python reference; both are only SQL-quoted (standard strings keep backslashes).
STRUCTURAL: list[tuple[object, str]] = [
    ({"b": 1, "a": {"d": True, "c": None}}, "keys sort recursively, no whitespace"),
    ({"Z": 1, "_": 2, "a": 3, "1": 4}, "keys sort in byte (C) order: digits, uppercase, underscore, lowercase"),
    (["quote \" backslash \\ newline \n tab \t unicode é del \x7f ctrl \x01"], "string escaping matches JSON.stringify / json.dumps(ensure_ascii=False)"),
]


def q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def render() -> str:
    expected = json.loads((FIXTURES / "expected.json").read_text(encoding="utf-8"))
    cases = sorted(p for p in FIXTURES.glob("case_*.json"))
    lines = [
        "-- GENERATED by services/calculator/scripts/export_canonical_sql_test.py from fixtures/synthetic/canonical. Do not edit by hand.",
        "-- Proves app.canonical_json(jsonb) hashes identically to the Python and TypeScript canonicalisers.",
        "begin;",
        "create extension if not exists pgtap with schema extensions;",
        f"select plan({len(cases) * 2 + len(STRUCTURAL)});",
        "",
    ]
    for case in cases:
        payload = json.loads(case.read_text(encoding="utf-8"))
        digest = canonical_hash(payload)
        if expected.get(case.name) != digest:
            raise SystemExit(f"expected.json is stale for {case.name}; regenerate it")
        literal = canonical_json(payload)
        lines.append(f"select is(app.sha256_canonical({q(literal)}::jsonb)::text, {q(digest)}, {q('sha256 ' + case.name + ' matches Python/TypeScript')});")
        lines.append(f"select is(app.canonical_json({q(literal)}::jsonb), {q(literal)}, {q('canonical text ' + case.name + ' is byte-identical')});")
    lines += ["", "-- Structural guarantees independent of the fixtures."]
    for payload, descr in STRUCTURAL:
        lines.append(f"select is(app.canonical_json({q(json.dumps(payload, ensure_ascii=False))}::jsonb), {q(canonical_json(payload))}, {q(descr)});")
    lines += ["", "select * from finish();", "rollback;", ""]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        if (OUT.read_text(encoding="utf-8") if OUT.exists() else "") != text:
            print(f"drift: {OUT} does not match the fixtures; run python scripts/export_canonical_sql_test.py")
            return 1
        print("canonical SQL test matches the fixtures")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
